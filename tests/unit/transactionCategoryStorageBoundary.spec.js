// Current CREATE behavior only. All database collaborators are inert; no app bootstrap.
import { test } from '@japa/runner'
import { readFile } from 'node:fs/promises'
import { runInNewContext } from 'node:vm'
import ts from 'typescript'
import { DateTime } from 'luxon'
import { TransactionType } from '../../common/ResponseTypes.ts'
import { updateCategoryTransfer } from '../../app/validation/Validators/categoryTransfer.ts'
import { calculateFunding, fundingCalculationInputs } from
  '../../client-src/Funding/calculateFunding.ts'
import { encodeTransferCategories } from '../../client-src/monetary.ts'
import { addMoneyCents, subtractMoneyCents, parseMoneyCents, formatMoneyCents } from
  '../../common/moneyCents.ts'
import { auditTransaction } from '../../scripts/auditTransactionCategoryCents.mjs'
import { Exception } from '@adonisjs/core/exceptions'
import { encodeMonetaryAmount, validateCategoryConservation, decodeCategoryAllocations } from
  '../../app/services/categoryAmountCodec.ts'
import { validateTransactionSplits } from '../../app/validation/transactionSplits.ts'

async function transferHandler(context) {
  const path = 'app/Controllers/Http/CategoriesController.ts'
  const source = ts.createSourceFile(path, await readFile(path, 'utf8'), ts.ScriptTarget.Latest,
    true)
  let expression
  function visit(node) {
    if (ts.isMethodDeclaration(node) && node.name.getText(source) === 'transfer') {
      expression = `(async function(${node.parameters.map((parameter) => parameter.getText(source))
        .join(',')}) ${node.body.getText(source)})`
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  if (!expression) throw new Error('Current transfer method not found')
  return runInNewContext(ts.transpileModule(expression, {
    compilerOptions: { target: ts.ScriptTarget.ES2022 },
  }).outputText, { addMoneyCents, subtractMoneyCents, parseMoneyCents, formatMoneyCents,
    ...context })
}

test.group('Transaction Category storage boundary — approved CREATE admission', () => {
  test('no-Pool funding generated by existing calculator is rejected by approved conservation', ({
    assert }) => {
    const calculated = calculateFunding(fundingCalculationInputs({
      1: { baseAmount: '10.00',
        fundingCategories: [{ categoryId: 2, amount: 100, percentage: true }],
        includeFundingTransfers: false },
    }), 99)
    assert.deepEqual(calculated.map(({ categoryId, amountCents }) => ({ categoryId, amountCents })),
      [{ categoryId: 1, amountCents: 1000 }, { categoryId: 2, amountCents: -1000 }])
    const submitted = encodeTransferCategories(calculated.map(({ amountCents, ...category }) => ({
      ...category, amount: formatMoneyCents(amountCents),
    })))
    const rows = decodeCategoryAllocations(submitted)
    assert.deepEqual(rows.map(({ categoryId, amount }) => ({ categoryId, amount })), [
      { categoryId: 1, amount: 10 }, { categoryId: 2, amount: -10 },
    ])
    validateTransactionSplits(0, rows)
    const result = auditTransaction({ id: 1, type: 2, categories: rows, links: [], poolIds: [99],
      deprecated: false })
    assert.equal(result.status, 'unsupported')
    assert.equal(result.reason, 'missing_pool_allocation')
    assert.throws(() => validateCategoryConservation(2, rows, undefined, 99),
      'Funding requires a Funding Pool allocation.')
  })
  test('transfer CREATE allows only funding and rebalance without creating an AccountTransaction')
    .with([0, 4, 5, 2, 3])
    .run(async ({ assert }, type) => {
      const events = []
      let created
      const owner = {
        async commit() { events.push('commit') },
        async rollback() { events.push('rollback') },
      }
      const budget = { id: 1, getFundingPoolCategory: async () => ({ id: 2 }) }
      const categories = new Map([1, 2].map((id) => [id, {
        id, balanceCents: parseMoneyCents('0.10'), async save() { events.push('category.save') },
      }]))
      const handler = await transferHandler({
        DateTime, TransactionType, Exception, updateCategoryTransfer, encodeMonetaryAmount,
          validateCategoryConservation,
        requestCategoryStorage: (model) => model, validateStoredCategoryConservation: async () =>
          undefined,
        transactionFields: {},
        db: { async transaction() { return owner } },
        Transaction: class {
          useTransaction(client) { assert.strictEqual(client, owner); return this }
          fill(values) { Object.assign(this, values); return this }
          async save() { events.push('transaction.create'); this.id = 42; created = { ...this };
            return this }
          serialize() { return { id: this.id, type: this.type, categories: this.categories } }
        },
        // CREATE must not use the replacement-only linkage query. No link-create stub exists.
        AccountTransaction: { query() { throw new Error(
          'Unexpected AccountTransaction query on CREATE') } },
        async authorizeCategories(budgetId, ids, { client }) {
          assert.equal(budgetId, 1)
          assert.deepEqual(Array.from(ids), [1, 2])
          assert.strictEqual(client, owner)
          events.push('authorize')
        },
        budgetCategories(budgetId, { client }) {
          assert.equal(budgetId, 1)
          assert.strictEqual(client, owner)
          return { where(key, id) { assert.equal(key, 'id'); return {
            async firstOrFail() { return categories.get(id) },
          } } }
        },
      })
      const run = () => handler({
        auth: { user: {
          useTransaction(client) { assert.strictEqual(client, owner) },
          related(name) {
            assert.equal(name, 'budget')
            return { query() { return { forUpdate() { return {
              async firstOrFail() { events.push('budget.gate'); return budget },
            } } } } }
          },
        } },
        request: {
          params() { return {} },
          async validateUsing(validator) {
            return validator.validate({ type, date: '2026-10-01',
              categories: [{ categoryId: 1, amount: '0.20' }, { categoryId: 2, amount: '-0.20' }] })
          },
        },
        logger: { error() { return undefined } },
      })
      if (![2, 3].includes(type)) {
        await assert.rejects(run,
          'Category transfers can create only funding or rebalance transactions.')
        assert.isUndefined(created)
        assert.notInclude(events, 'category.save')
        assert.notInclude(events, 'commit')
        assert.include(events, 'rollback')
        return
      }
      const response = await run()
      assert.equal(created.type, type)
      assert.equal(created.budgetId, 1)
      assert.equal(response.data.transaction.type, type)
      assert.strictEqual(categories.get(1).balanceCents, parseMoneyCents('0.30'))
      assert.strictEqual(categories.get(2).balanceCents, parseMoneyCents('-0.10'))
      assert.include(events, 'commit')
      assert.notInclude(events, 'rollback')
      assert.isBelow(events.indexOf('budget.gate'), events.indexOf('transaction.create'))
    })
})
